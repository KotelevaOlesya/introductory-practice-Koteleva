# --------------------------------------------------
# Упражнение 1. Результат периода (прибыль/убыток)
# --------------------------------------------------
profit = float(input("Введите прибыль за месяц: "))

if profit > 0:
    print("Результат: Прибыль")
elif profit < 0:
    print("Результат: Убыток")
else:
    print("Результат: Безубыточность")
print()

# --------------------------------------------------
# Упражнение 2. Категория бизнеса по выручке
# --------------------------------------------------
revenue = float(input("Введите годовую выручку (млн руб.): "))

if revenue < 1:
    print("Категория: Микробизнес")
elif revenue < 10:
    print("Категория: Малый")
elif revenue < 100:
    print("Категория: Средний")
else:
    print("Категория: Крупный")
print()

# --------------------------------------------------
# Упражнение 3. Расчёт НДФЛ (13% или 15%)
# --------------------------------------------------
salary = float(input("Введите зарплату: "))

if salary <= 50000:
    tax_rate = 13
else:
    tax_rate = 15

tax = salary * tax_rate / 100
salary_after = salary - tax
print(f"Налог: {tax:.2f} руб.")
print(f"Сумма на руки: {salary_after:.2f} руб.")
print()

# --------------------------------------------------
# Упражнение 4. Таблица умножения ставки
# --------------------------------------------------
rate = float(input("Введите процентную ставку: "))
print(f"Таблица умножения ставки {rate}%:")

for i in range(1, 13):
    result = rate * i
    print(f"{rate} × {i} = {result}")
print()

# --------------------------------------------------
# Упражнение 5. Анализ цен (дорого/не дорого)
# --------------------------------------------------
prices = [150, 320, 45, 500, 270]
print("Анализ цен:")

for price in prices:
    if price > 300:
        print(f"{price} руб. — ДОРОГО")
    else:
        print(f"{price} руб. — нормально")