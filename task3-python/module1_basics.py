# --------------------------------------------------
# Упражнение 1. Карточка сотрудника
# --------------------------------------------------
name = "Анна Смирнова"
age = 28
salary = 75000.50
is_working = True

print("--- Карточка сотрудника ---")
print("Имя:", name)
print("Возраст:", age)
print("Зарплата:", salary, "руб.")
print("Работает в данный момент:", is_working)
print()

# --------------------------------------------------
# Упражнение 2. Приветствие
# --------------------------------------------------
user_name = input("Введите имя сотрудника: ")
city = input("Введите город: ")
print(f"Сотрудник {user_name} работает в офисе {city}")
print()

# --------------------------------------------------
# Упражнение 3. Стоимость заказа
# --------------------------------------------------
price = float(input("Введите цену товара: "))
quantity = int(input("Введите количество: "))
total_cost = price * quantity
print(f"Итоговая стоимость заказа: {total_cost} руб.")
print()

# --------------------------------------------------
# Упражнение 4. Доход по вкладу
# --------------------------------------------------
deposit = float(input("Введите сумму вклада (руб.): "))
rate = float(input("Введите годовую ставку (%): "))
year_income = deposit * (rate / 100)
print(f"Доход за год: {year_income:.2f} руб.")
print()

# --------------------------------------------------
# Упражнение 5. Конвертер валюты (рубли → доллары)
# --------------------------------------------------
usd_rate = float(input("Введите курс доллара: "))
rub_amount = float(input("Введите сумму в рублях: "))
usd_amount = rub_amount / usd_rate
print(f"{rub_amount} руб. = {usd_amount:.2f} USD")