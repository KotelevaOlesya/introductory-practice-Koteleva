# Итоговая мини-программа
# Вариант 1. Калькулятор рентабельности
# Описание: пользователь вводит название компании, выручку и затраты.
# Программа вычисляет прибыль и рентабельность продаж,
# выводит мини-отчёт с оценкой: высокая (>20%), средняя (10-20%), низкая (<10%).

# --------------------------------------------------
# Функция расчёта рентабельности
# --------------------------------------------------
def calculate_profitability(revenue, costs):
    """
    Принимает выручку и затраты.
    Возвращает прибыль и рентабельность в процентах.
    """
    profit = revenue - costs
    if revenue > 0:
        profitability = (profit / revenue) * 100
    else:
        profitability = 0
    return profit, profitability

# --------------------------------------------------
# Функция оценки уровня рентабельности
# --------------------------------------------------
def get_rating(profitability):
    """Возвращает текстовую оценку на основе процента рентабельности"""
    if profitability > 20:
        return "высокая"
    elif profitability >= 10:
        return "средняя"
    else:
        return "низкая"

# --------------------------------------------------
# Основная часть программы (пример использования)
# --------------------------------------------------
print("=" * 50)
print("       КАЛЬКУЛЯТОР РЕНТАБЕЛЬНОСТИ")
print("=" * 50)

# Ввод данных (разные типы: str, float)
company_name = input("Введите название компании: ")
revenue = float(input("Введите выручку (руб.): "))
costs = float(input("Введите затраты (руб.): "))

# Расчёт
profit, profitability = calculate_profitability(revenue, costs)
rating = get_rating(profitability)

# Вывод отчёта
print("\n" + "=" * 50)
print("           МИНИ-ОТЧЁТ")
print("=" * 50)
print(f"Компания: {company_name}")
print(f"Выручка: {revenue:.2f} руб.")
print(f"Затраты: {costs:.2f} руб.")
print(f"Прибыль: {profit:.2f} руб.")
print(f"Рентабельность продаж: {profitability:.2f}%")
print(f"Оценка: {rating}")

# --------------------------------------------------
# Демонстрация цикла for (необязательный блок для проверки)
# --------------------------------------------------
print("\n" + "=" * 50)
print("   Анализ при разных уровнях выручки (демо-цикл)")
print("=" * 50)
test_revenues = [50000, 100000, 150000]
for test_rev in test_revenues:
    test_profit, test_prof = calculate_profitability(test_rev, costs)
    print(f"Выручка {test_rev}: прибыль {test_profit:.2f}, рентабельность {test_prof:.2f}%")